def search_teachings(query: str, top_k: int = 3) -> list[dict]:
    query_words = set(query.lower().split())
    scored = []
    for teaching in BUDDHIST_TEACHINGS:
        tag_set = set(teaching["tags"])
        text_words = set(teaching["text"].lower().split())
        tag_score = len(query_words & tag_set) * 3
        text_score = len(query_words & text_words)
        total = tag_score + text_score
        if total > 0:
            scored.append((total, teaching))
    scored.sort(key=lambda x: x[0], reverse=True)
    return [t for _, t in scored[:top_k]]


def format_context(teachings: list[dict]) -> str:
    if not teachings:
        return ""
    parts = []
    for t in teachings:
        parts.append(f"[{t['id']}]\n{t['text']}")
    return "\n\n".join(parts)
